// Scorecard: runs the engine on the hand-written demo notes and on the
// fixed-seed synthetic corpus, and counts hits, misses and false flags per
// check. `npm run scorecard` writes the result into README.md between the
// scorecard markers; test/scorecard.test.js fails if the README and a fresh
// run ever disagree, so the table cannot be edited by hand.

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { parseDeliveryNote } from '../src/lib/parse.js';
import { checkDeliveryNote, CODES } from '../src/lib/check.js';
import { DEMO_NOTES, demoNoteText, seedHistory } from '../src/lib/demo.js';
import { supplierKey } from '../src/lib/text.js';
import { CORPUS_SEED, CORPUS_SIZE, generateCorpus, INJECTIONS } from '../test/corpus.js';
import { formatMoney } from '../src/lib/num.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const START = '<!-- scorecard:start -->';
const END = '<!-- scorecard:end -->';

const history = seedHistory();
const historyFor = (name) => (name ? history.filter((e) => e.supplierKey === supplierKey(name)) : []);

function found(result) {
  const lineNos = result.lines.map((l) => l.lineNo);
  return result.discrepancies
    .filter((d) => d.severity !== 'info' && d.code !== 'PARSE_SKIPPED_LINE')
    .map((d) => ({ code: d.code, line: lineNos.includes(d.lineNo) ? lineNos.indexOf(d.lineNo) : null }));
}

const same = (a, b) => a.code === b.code && a.line === b.line;

export function computeScorecard({ seed } = {}) {
  // Demo notes: exact expected findings, status and money.
  const demo = DEMO_NOTES.map((spec) => {
    const note = parseDeliveryNote(demoNoteText(spec));
    const r = checkDeliveryNote(note, { history: historyFor(spec.supplier), duplicateOf: spec.duplicateOfDemo ? 'first booking' : null });
    const got = found(r);
    const want = spec.expected.codes;
    const ok = got.length === want.length && want.every((w) => got.some((g) => same(g, w))) && r.status === spec.expected.status && r.amountInDispute === spec.expected.amountInDispute;
    return { id: spec.id, title: spec.title, format: note.format, expected: want.map((w) => w.code), status: r.status, amount: r.amountInDispute, ok };
  });

  // Synthetic corpus: duplicates are detected from the parsed supplier and note number, as the app does.
  const corpus = generateCorpus(seed ? { seed } : {});
  const perCode = Object.fromEntries(INJECTIONS.map((c) => [c, { injected: 0, found: 0, missed: 0, falseFlags: 0 }]));
  const formats = {};
  let cleanNotes = 0;
  let cleanOk = 0;
  let notesAllRight = 0;
  const booked = new Map();
  for (const c of corpus) {
    const note = parseDeliveryNote(c.text);
    const k = `${supplierKey(note.supplier)}|${note.number}`;
    const duplicateOf = booked.get(k) ?? null;
    if (!duplicateOf) booked.set(k, c.id);
    const r = checkDeliveryNote(note, { history: historyFor(note.supplier), duplicateOf });
    const got = found(r);
    formats[note.format] = (formats[note.format] ?? 0) + 1;
    for (const t of c.truth) {
      perCode[t.code].injected += 1;
      if (got.some((g) => same(g, t))) perCode[t.code].found += 1;
      else perCode[t.code].missed += 1;
    }
    let extra = 0;
    for (const g of got) {
      if (!c.truth.some((t) => same(t, g))) {
        extra += 1;
        if (!perCode[g.code]) perCode[g.code] = { injected: 0, found: 0, missed: 0, falseFlags: 0 };
        perCode[g.code].falseFlags += 1;
      }
    }
    if (c.clean) {
      cleanNotes += 1;
      if (r.status === 'OK') cleanOk += 1;
    }
    if (extra === 0 && c.truth.every((t) => got.some((g) => same(g, t)))) notesAllRight += 1;
  }
  const totals = Object.values(perCode).reduce((a, s) => ({ injected: a.injected + s.injected, found: a.found + s.found, missed: a.missed + s.missed, falseFlags: a.falseFlags + s.falseFlags }), { injected: 0, found: 0, missed: 0, falseFlags: 0 });
  return { demo, perCode, totals, formats, cleanNotes, cleanOk, notes: corpus.length, notesAllRight, seed: seed ?? CORPUS_SEED, size: CORPUS_SIZE };
}

export function renderScorecard(s) {
  const out = [];
  out.push(`Generated by \`npm run scorecard\` from the test data. Do not edit by hand; \`npm test\` fails if this table and a fresh run disagree.`);
  out.push('');
  out.push('Demo notes, the seven that "Load demo data" creates:');
  out.push('');
  out.push('| Note | Format read | Expected findings | Status | In dispute | Match |');
  out.push('|---|---|---|---|---|---|');
  for (const d of s.demo) out.push(`| ${d.title} | ${d.format} | ${d.expected.length ? d.expected.join(', ') : 'none'} | ${d.status} | ${formatMoney(d.amount)} | ${d.ok ? 'yes' : 'NO'} |`);
  out.push('');
  out.push(`Synthetic corpus: ${s.notes} notes from a fixed seed (${s.seed}), ${Object.entries(s.formats).map(([f, n]) => `${n} ${f}`).join(', ')}. One note in five is clean; the others carry one or two injected problems.`);
  out.push('');
  out.push('| Check | Injected | Found | Missed | False flags |');
  out.push('|---|---|---|---|---|');
  for (const [code, v] of Object.entries(s.perCode)) out.push(`| ${CODES[code] ?? code} (\`${code}\`) | ${v.injected} | ${v.found} | ${v.missed} | ${v.falseFlags} |`);
  out.push(`| All checks | ${s.totals.injected} | ${s.totals.found} | ${s.totals.missed} | ${s.totals.falseFlags} |`);
  out.push('');
  out.push(`Clean notes marked OK: ${s.cleanOk} of ${s.cleanNotes}. Notes where every finding was right and nothing extra was flagged: ${s.notesAllRight} of ${s.notes}.`);
  out.push('');
  out.push('What this does and does not show: the corpus is generated by the same project, so it proves the parser and the checks hold up across formats, decimal styles, Spanish and English headers and mixed problems. It says nothing about accuracy on real suppliers\' paperwork, which I have not measured.');
  return out.join('\n');
}

export function readmeSection(readme) {
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < 0) return null;
  return readme.slice(a + START.length, b).trim();
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const s = computeScorecard();
  const md = renderScorecard(s);
  const readmePath = path.join(ROOT, 'README.md');
  const readme = readFileSync(readmePath, 'utf8');
  const a = readme.indexOf(START);
  const b = readme.indexOf(END);
  if (a < 0 || b < 0) throw new Error('README.md has no scorecard markers');
  writeFileSync(readmePath, `${readme.slice(0, a + START.length)}\n${md}\n${readme.slice(b)}`);
  console.log(md);
}
